import { test, expect } from "@playwright/test";
test("workspace edits survive and pipeline changes apply automatically", async ({ page }) => {
  await page.goto("/");
  await expect(page.getByRole("button", { name: "Build app", exact: true })).toBeEnabled();
  await expect(page.getByRole("tab", { name: "Development", exact: true })).toHaveAttribute("aria-selected", "true");
  await expect(page.getByRole("button", { name: "Execute Plan" })).toHaveCount(0);
  await page.getByRole("button", { name: "Text", exact: true }).click();
  await page.getByPlaceholder("Block title…").last().fill("Inspiration");
  await page.getByPlaceholder("Write…").last().fill("Definitions survive removing the pipeline.");
  await expect(page.getByRole("status", { name: "All changes saved" })).toBeVisible();
  await page.reload();
  await expect(page.getByPlaceholder("Block title…").last()).toHaveValue("Inspiration");
  await expect(page.getByPlaceholder("Write…").last()).toHaveValue("Definitions survive removing the pipeline.");
  await page.getByRole("tab", { name: "Pipeline", exact: true }).click();
  await expect(page.getByRole("button", { name: /Say hello to/ })).toHaveCount(0);
  await expect(page.getByRole("button", { name: /Give robot/ })).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Pause workshop animations", exact: true })).toHaveCount(0);
  await page.getByRole("button", { name: "+ Advanced", exact: true }).click();
  await expect(page.getByRole("checkbox", { name: "Review full specification" })).toBeVisible();
  await expect(page.getByRole("button", { name: "Build with these options" })).toBeVisible();
  await page.getByRole("button", { name: "− Advanced", exact: true }).click();
  await page.getByRole("button", { name: "Build app", exact: true }).click();
  await page.getByRole("dialog",{name:"Confirm action"}).getByRole("button",{name:"Keep working"}).click();
  await expect(page.getByRole("button", { name: "Build app", exact: true })).toBeEnabled();
  await page.getByRole("button", { name: "Build app", exact: true }).click();
  await page.getByRole("dialog",{name:"Confirm action"}).getByRole("button",{name:"Continue",exact:true}).click();
  await expect(page.getByRole("tab", { name: "Pipeline", exact: true })).toHaveAttribute("aria-selected", "true");
  await expect(page.getByRole("button", { name: "Build app", exact: true })).toBeDisabled();
  await expect(page.getByRole("list", { name: "Pipeline progress" })).toBeVisible();
  await page.getByRole("tab", { name: "Development", exact: true }).click();
  await expect(page.getByPlaceholder("Write…").last()).toHaveValue("Definitions survive removing the pipeline.");
  await page.getByRole("tab", { name: "Pipeline", exact: true }).click();
  await expect(page.getByRole("region", { name: "App workshop" })).toBeVisible();
  await expect(page.getByRole("button", { name: "Restore previous version", exact:true })).toBeVisible({timeout:30000});
  await page.screenshot({path:"output/ui-refactor/pipeline.png",fullPage:true});
  await expect(page.getByRole("button", { name: "Accept changes" })).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Review changes",exact:true })).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Build changes", exact: true })).toBeEnabled();
  await page.getByRole("button", { name: "Settings", exact: true }).click();
  await expect(page.getByRole("button", { name: "Rebuild project" })).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Refine", exact: true })).toHaveCount(0);
  await page.getByRole("button", { name: "Close settings" }).click();
  await page.getByRole("button", { name: "Debug", exact: true }).click();
  await page.getByRole("button", { name: "Pipeline history", exact: true }).click();
  await expect(page.getByText("No saved pipeline history.")).toBeVisible();
});
